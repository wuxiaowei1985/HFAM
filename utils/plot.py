import matplotlib.pyplot as plt
import pandas as pd

def plot_training_curve(csv_path, save_dir):
    history = pd.read_csv(csv_path)
    plt.figure(figsize=(8, 5))
    plt.plot(history["epoch"], history["train_loss"], label="Train Total Loss", linewidth=2)
    plt.plot(history["epoch"], history["val_loss"], label="Validation Total Loss", linewidth=2)
    plt.xlabel("Epoch")
    plt.ylabel("Loss")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.savefig(save_dir / "total_loss_curve.png", dpi=300)
    plt.close()

    plt.figure(figsize=(8, 5))
    plt.plot(history["epoch"], history["train_sample_acc"] * 100, label="Train Sample Accuracy", linewidth=2)
    plt.plot(history["epoch"], history["val_sample_acc"] * 100, label="Validation Sample Accuracy", linewidth=2)
    plt.xlabel("Epoch")
    plt.ylabel("Sample Accuracy (%)")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.savefig(save_dir / "sample_accuracy_curve.png", dpi=300)
    plt.close()

    plt.figure(figsize=(8, 5))
    plt.plot(history["epoch"], history["train_frame_acc"] * 100, label="Train Frame Accuracy", linewidth=2)
    plt.plot(history["epoch"], history["val_frame_acc"] * 100, label="Validation Frame Accuracy", linewidth=2)
    plt.xlabel("Epoch")
    plt.ylabel("Frame Accuracy (%)")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.savefig(save_dir / "frame_accuracy_curve.png", dpi=300)
    plt.close()

    plt.figure(figsize=(8, 5))
    plt.plot(history["epoch"], history["lr"], label="Learning Rate", linewidth=2)
    plt.xlabel("Epoch")
    plt.ylabel("Learning Rate")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.savefig(save_dir / "learning_rate_curve.png", dpi=300)
    plt.close()